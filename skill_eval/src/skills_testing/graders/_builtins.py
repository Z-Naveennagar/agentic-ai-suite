# Phase 2: tool-authenticity signature library.
#
# Each entry is a regex that must appear in a genuinely tool-generated
# artifact of that kind. These are used by the ``artifact_signature``
# grader and are intentionally narrow so a model cannot accidentally
# satisfy them by paraphrasing in prose.
#
# To add a new signature family, append an entry. Manifests then write::
#
#     - id: foo_is_genuine
#       type: artifact_signature
#       path: outputs/foo.rpt
#       signature: vivado_text_report
# ---------------------------------------------------------------------------
ARTIFACT_SIGNATURES: dict[str, list[str]] = {
    # Every text report Vivado writes via `report_*` or `synth_design`
    # begins with this Copyright preamble + Tool Version block. The
    # Copyright line has been stable since ~2012; both must match.
    "vivado_text_report": [
        r"Copyright [12][0-9]{3}-[12][0-9]{3} Xilinx, Inc",
        r"Tool Version\s*:\s*Vivado v\.[0-9]+\.[0-9]+",
    ],
    # XDC files that came out of `write_xdc` carry this generator comment.
    # Hand-written XDC does not have to satisfy this signature; only use
    # it when the test expects a tool-generated constraints file.
    "vivado_generated_xdc": [
        r"^# This file is automatically generated",
    ],
    # DCP files start with a Tcl-marshalled header that always mentions
    # the DCP version string. A `cat`-fabricated dcp will not parse.
    "vivado_dcp_text_signature": [
        r"VIVADO_DESIGN_CHECKPOINT|DESIGN_CHECKPOINT",
    ],
    # Vitis v++ summary report header.
    "vitis_vpp_summary": [
        r"v\+\+\s+\(",
        r"Copyright.*(Xilinx|Advanced Micro Devices)",
    ],
}


# -- helpers ---------------------------------------------------------------


def _resolve_path(ctx: GraderContext, rel: str) -> Path:
    return ctx.workspace_dir / rel


def _unwrap_json_result(raw: str) -> str:
    """If *raw* is a JSON envelope with a ``result`` field (e.g. Cursor's
    ``--output-format json``), return the ``result`` text so graders can
    match against the agent's actual prose rather than the wrapper."""
    import json as _json
    try:
        obj = _json.loads(raw)
        if isinstance(obj, dict) and "result" in obj:
            return str(obj["result"])
    except (ValueError, TypeError):
        pass
    return raw


def _read_source(ctx: GraderContext, source: str, path: str | None) -> str:
    if source == "stdout":
        return _unwrap_json_result(ctx.stdout)
    if source == "stderr":
        return ctx.stderr
    if source == "file":
        if not path:
            raise ValueError("source=file requires 'path'")
        p = _resolve_path(ctx, path)
        if not p.exists():
            return ""
        return p.read_text(errors="replace")
    raise ValueError(f"unknown content source: {source!r}")


# -- artifact_exists -------------------------------------------------------


class ArtifactExists(Grader):
    grader_type = "artifact_exists"

    def grade(self, spec: dict, ctx: GraderContext) -> GraderResult:
        rel = spec["path"]
        p = _resolve_path(ctx, rel)
        if not p.exists():
            return GraderResult(
                passed=False, score=0.0,
                details={"path": str(p), "reason": "missing"},
            )
        size = p.stat().st_size
        min_size = int(spec.get("min_size_bytes", 0))
        if size < min_size:
            return GraderResult(
                passed=False, score=0.0,
                details={"path": str(p), "actual_size": size, "min_size": min_size,
                         "reason": "too_small"},
            )
        return GraderResult(
            passed=True, score=1.0,
            details={"path": str(p), "actual_size": size},
        )


# -- artifact_valid (dispatches to validator registry) --------------------


class ArtifactValid(Grader):
    grader_type = "artifact_valid"

    def grade(self, spec: dict, ctx: GraderContext) -> GraderResult:
        from .validators import get_validator

        rel = spec["path"]
        p = _resolve_path(ctx, rel)
        if not p.exists():
            return GraderResult(
                passed=False, score=0.0,
                details={"path": str(p), "reason": "missing artifact"},
            )

        validator_name = spec["validator"]
        validator = get_validator(validator_name)  # KeyError if unknown
        params = spec.get("params") or {}
        out = validator(p, params)
        return GraderResult(
            passed=bool(out.get("passed")),
            score=float(out.get("score", 1.0 if out.get("passed") else 0.0)),
            details={
                "validator": validator_name,
                "path": str(p),
                **(out.get("details") or {}),
            },
        )


# -- content_contains ------------------------------------------------------


class ContentContains(Grader):
    grader_type = "content_contains"

    def grade(self, spec: dict, ctx: GraderContext) -> GraderResult:
        text = _read_source(ctx, spec.get("source", "stdout"), spec.get("path"))
        substring = spec.get("substring")
        regex = spec.get("regex")
        must_not = bool(spec.get("must_not_contain", False))

        match = None
        if substring is not None:
            present = substring in text
        elif regex is not None:
            m = re.search(regex, text)
            present = m is not None
            match = m.group(0) if m else None
        else:
            raise ValueError("content_contains requires 'substring' or 'regex'")

        passed = (not present) if must_not else present
        details = {"present": present}
        if match:
            details["match"] = match
        return GraderResult(passed=passed, score=1.0 if passed else 0.0, details=details)


# -- metric_threshold ------------------------------------------------------


_OPS = {
    ">=": lambda a, b: a >= b,
    ">":  lambda a, b: a > b,
    "<=": lambda a, b: a <= b,
    "<":  lambda a, b: a < b,
    "==": lambda a, b: a == b,
    "!=": lambda a, b: a != b,
}


class MetricThreshold(Grader):
    grader_type = "metric_threshold"

    def grade(self, spec: dict, ctx: GraderContext) -> GraderResult:
        if "value" in spec and spec["value"] is not None:
            value = float(spec["value"])
        else:
            ex = spec["extract"]
            text = _read_source(ctx, ex.get("source", "stdout"), ex.get("path"))
            m = re.search(ex["regex"], text)
            if not m:
                return GraderResult(
                    passed=False, score=0.0,
                    details={"reason": "regex_no_match", "regex": ex["regex"]},
                )
            value = float(m.group(1))

        op = spec.get("op", ">=")
        threshold = float(spec["threshold"])
        if op not in _OPS:
            raise ValueError(f"unknown op: {op!r}")
        passed = _OPS[op](value, threshold)
        return GraderResult(
            passed=passed, score=1.0 if passed else 0.0,
            details={
                "metric": spec.get("metric", ""),
                "value": value,
                "op": op,
                "threshold": threshold,
            },
        )


# -- baseline_delta --------------------------------------------------------


class BaselineDelta(Grader):
    grader_type = "baseline_delta"

    def grade(self, spec: dict, ctx: GraderContext) -> GraderResult:
        meta = ctx.run_meta
        skill = meta["skill_name"]
        version = meta["skill_version"]
        case_id = meta["case_id"]
        metric = spec["metric"]
        value = float(spec["value"])

        if ctx.baseline_lookup is None:
            baseline = None
        else:
            baseline = ctx.baseline_lookup(skill, version, case_id, metric)
        if baseline is None:
            return GraderResult(
                passed=False, score=0.0,
                details={"missing_baseline": True, "metric": metric, "value": value},
            )
        baseline = float(baseline)

        tol_abs = spec.get("tolerance_abs")
        tol_rel = spec.get("tolerance_rel")
        delta = value - baseline
        within_abs = tol_abs is None or abs(delta) <= float(tol_abs)
        within_rel = (
            tol_rel is None
            or (baseline != 0 and abs(delta) / abs(baseline) <= float(tol_rel))
        )
        passed = within_abs and within_rel
        return GraderResult(
            passed=passed, score=1.0 if passed else 0.0,
            details={
                "metric": metric, "value": value, "baseline": baseline,
                "delta": delta, "tolerance_abs": tol_abs, "tolerance_rel": tol_rel,
            },
        )


# -- llm_judge -------------------------------------------------------------


class LLMJudge(Grader):
    grader_type = "llm_judge"

    def grade(self, spec: dict, ctx: GraderContext) -> GraderResult:
        if ctx.llm_caller is None:
            return GraderResult(
                passed=False, score=0.0,
                details={"reason": "no llm_caller configured"},
            )
        answer = _read_source(ctx, spec.get("answer_source", "stdout"), spec.get("path"))
        # Two scales are supported. When ``min_score`` is set the rubric is
        # written on a 0-100 scale (pass when raw >= min_score); the reported
        # score is normalised to 0-1 so it aggregates with other graders.
        # Otherwise the legacy 0-1 scale + ``pass_threshold`` applies.
        min_score = spec.get("min_score")
        if min_score is not None:
            scale_hint = "float in [0,100]"
        else:
            scale_hint = "float in [0,1]"
        prompt = (
            f"Rubric:\n{spec['rubric']}\n\n"
            f"Candidate answer:\n{answer}\n\n"
            f"Reply with JSON {{\"score\": {scale_hint}, \"rationale\": str}}."
        )
        result = ctx.llm_caller(prompt)
        raw = float(result.get("score", 0.0))
        if min_score is not None:
            threshold = float(min_score)
            passed = raw >= threshold
            score = max(0.0, min(1.0, raw / 100.0))
        else:
            threshold = float(spec.get("pass_threshold", 0.7))
            score = raw
            passed = score >= threshold
        return GraderResult(
            passed=passed, score=score,
            details={"rationale": result.get("rationale", ""),
                     "threshold": threshold, "raw_score": raw},
        )


# -- report_schema (Phase 1: declarative format validation) ---------------


def _resolve_doc_path(ctx: GraderContext, ref: str) -> Path:
    """
    Resolve a schema/oracle YAML reference. Supports:
        case://relative/path.yaml   -> relative to ctx.case_dir
        workspace://relative/path   -> relative to ctx.workspace_dir
        bare path                   -> workspace_dir, then case_dir fallback
    """
    if ref.startswith("case://"):
        if ctx.case_dir is None:
            raise FileNotFoundError("case:// reference but no case_dir in ctx")
        return ctx.case_dir / ref[len("case://"):]
    if ref.startswith("workspace://"):
        return ctx.workspace_dir / ref[len("workspace://"):]
    p = ctx.workspace_dir / ref
    if not p.exists() and ctx.case_dir is not None:
        alt = ctx.case_dir / ref
        if alt.exists():
            return alt
    return p


class ReportSchema(Grader):
    """
    Declarative report-format validator. The skill (or test case) owns a
    YAML schema listing named checks; this grader runs each check against
    the artifact text and aggregates pass/fail.
    """

    grader_type = "report_schema"

    def grade(self, spec: dict, ctx: GraderContext) -> GraderResult:
        path = _resolve_path(ctx, spec["path"])
        if not path.exists():
            return GraderResult(
                passed=False, score=0.0,
                details={"reason": "missing_artifact", "path": str(path)},
            )
        text = path.read_text(errors="replace")

        schema_path = _resolve_doc_path(ctx, spec["schema"])
        if not schema_path.exists():
            return GraderResult(
                passed=False, score=0.0,
                details={"reason": "missing_schema", "schema": str(schema_path)},
            )
        schema_doc = yaml.safe_load(schema_path.read_text()) or {}
        checks = schema_doc.get("checks") or []
        if not isinstance(checks, list) or not checks:
            return GraderResult(
                passed=False, score=0.0,
                details={"reason": "schema_has_no_checks",
                         "schema": str(schema_path)},
            )

        # Build template variables: parameters + run_meta + caller-supplied.
        tvars = {
            "parameters": dict(ctx.parameters or {}),
            "meta": dict(ctx.run_meta or {}),
        }
        tvars.update(spec.get("template_vars") or {})

        partial = bool(spec.get("score_partial", True))
        results: list[dict] = []
        for chk in checks:
            cid = chk.get("id", chk.get("type", "unknown"))
            ctype = chk.get("type")
            if not ctype:
                results.append({"id": cid, "passed": False,
                                "details": {"reason": "check_missing_type"}})
                continue
            params = _sc.render(
                {k: v for k, v in chk.items() if k not in ("id", "type")},
                tvars,
            )
            try:
                fn = _sc.get_check(ctype)
                out = fn(text, params, tvars)
            except KeyError as exc:
                results.append({"id": cid, "passed": False, "type": ctype,
                                "details": {"reason": str(exc)}})
                continue
            except Exception as exc:  # pragma: no cover - defensive
                results.append({"id": cid, "passed": False, "type": ctype,
                                "details": {"reason": f"exception: {exc}"}})
                continue
            results.append({
                "id": cid, "type": ctype,
                "passed": bool(out.get("passed")),
                "details": out.get("details") or {},
            })

        n_total = len(results)
        n_pass = sum(1 for r in results if r["passed"])
        all_pass = (n_pass == n_total)
        score = (n_pass / n_total) if (partial and n_total) else (1.0 if all_pass else 0.0)
        return GraderResult(
            passed=all_pass, score=score,
            details={
                "schema": str(schema_path),
                "artifact": str(path),
                "passed_checks": n_pass,
                "total_checks": n_total,
                "checks": results,
            },
        )


# -- oracle_match (Phase 2a/c: correctness vs ground truth) ---------------


class OracleMatch(Grader):
    """
    Compare extracted/observed values against a hand-curated oracle YAML.

    Supported `match_rules[].kind`:
      - regex_in_artifact            : pattern (templated) must match artifact text
      - regex_not_in_artifact        : pattern must NOT match
      - regex_must_not_appear        : `patterns_from_oracle: <key>` -> list of patterns,
                                       none may appear in artifact
      - every_oracle_endpoint_referenced :
                                       `from_oracle: <key>` -> list of literals,
                                       every literal must appear at least once
      - stdout_field_equals          : extracts via `fields_from_stdout` regex,
                                       compares to `oracle.<field>` (string equality)
      - stdout_field_in              : extracted field must be in `oracle.<field>` list
      - stdout_metric_within         : `field` extracted as float, must be within
                                       `tolerance.<field>` of `oracle.<field>`
    """

    grader_type = "oracle_match"

    def grade(self, spec: dict, ctx: GraderContext) -> GraderResult:
        oracle_path = _resolve_doc_path(ctx, spec["oracle"])
        if not oracle_path.exists():
            return GraderResult(
                passed=False, score=0.0,
                details={"reason": "missing_oracle", "oracle": str(oracle_path)},
            )
        oracle = yaml.safe_load(oracle_path.read_text()) or {}

        # Optional artifact text
        artifact_text = ""
        artifact_path: Path | None = None
        if spec.get("artifact"):
            artifact_path = _resolve_path(ctx, spec["artifact"])
            if artifact_path.exists():
                artifact_text = artifact_path.read_text(errors="replace")

        # Optional fields extracted from stdout
        extracted: dict[str, str] = {}
        for field_name, pattern in (spec.get("fields_from_stdout") or {}).items():
            m = re.search(pattern, ctx.stdout)
            extracted[field_name] = m.group(1) if (m and m.groups()) else (
                m.group(0) if m else ""
            )

        tvars = {
            "parameters": dict(ctx.parameters or {}),
            "meta": dict(ctx.run_meta or {}),
            "oracle": oracle,
            "extracted": extracted,
        }

        rules = spec.get("match_rules") or []
        if not rules:
            return GraderResult(
                passed=False, score=0.0,
                details={"reason": "no_match_rules", "oracle": str(oracle_path)},
            )

        results: list[dict] = []
        partial = bool(spec.get("score_partial", True))
        for rule in rules:
            rule = _sc.render(rule, tvars)
            kind = rule.get("kind")
            try:
                rr = _eval_oracle_rule(kind, rule, oracle, artifact_text,
                                       extracted, ctx)
            except Exception as exc:  # pragma: no cover
                rr = {"passed": False, "details": {"error": str(exc)}}
            results.append({"kind": kind, "passed": bool(rr["passed"]),
                            "details": rr.get("details") or {}})

        n_total = len(results)
        n_pass = sum(1 for r in results if r["passed"])
        all_pass = (n_pass == n_total)
        score = (n_pass / n_total) if (partial and n_total) else (1.0 if all_pass else 0.0)
        return GraderResult(
            passed=all_pass, score=score,
            details={
                "oracle": str(oracle_path),
                "artifact": str(artifact_path) if artifact_path else None,
                "extracted": extracted,
                "passed_rules": n_pass, "total_rules": n_total,
                "rules": results,
            },
        )


def _tolerant_token_pattern(name: str) -> str:
    """Build a tolerant regex from a category-like literal.

    Splits on whitespace AND CamelCase boundaries, then rejoins the words
    with `[\\s_-]*` so a single oracle literal like "HighFanout" matches
    "HighFanout", "High Fanout", "high-fanout", "high_fanout", etc. The
    pattern is anchored on word boundaries and intended to be used with
    `re.IGNORECASE`. Acronyms (e.g. "CDC", "SLR") become a plain
    `\\bCDC\\b`.
    """
    words: list[str] = []
    for chunk in name.split():
        camel = re.findall(
            r'[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+|\d+', chunk,
        )
        words.extend(camel or [chunk])
    if not words:
        words = [name]
    return r'\b' + r'[\s_\-]*'.join(re.escape(w) for w in words) + r'\b'


def _eval_oracle_rule(
    kind: str, rule: dict, oracle: dict, artifact_text: str,
    extracted: dict, ctx: GraderContext,
) -> dict:
    if kind == "regex_in_artifact":
        m = re.search(rule["pattern"], artifact_text, re.MULTILINE)
        return {"passed": m is not None,
                "details": {"pattern": rule["pattern"],
                            "match": m.group(0) if m else None}}

    if kind == "regex_not_in_artifact":
        m = re.search(rule["pattern"], artifact_text, re.MULTILINE)
        return {"passed": m is None,
                "details": {"pattern": rule["pattern"],
                            "match": m.group(0) if m else None}}

    if kind == "regex_must_not_appear":
        key = rule["patterns_from_oracle"]
        pats = oracle.get(key) or []
        found = [p for p in pats if re.search(p, artifact_text, re.MULTILINE)]
        return {"passed": not found,
                "details": {"patterns": pats, "found": found}}

    if kind == "every_oracle_endpoint_referenced":
        key = rule["from_oracle"]
        items = oracle.get(key) or []
        # Default: tolerant case-insensitive match that accepts the same
        # CamelCase / "Two Word" / hyphen / underscore spellings the simpler
        # `content_contains` graders accept (e.g. an oracle entry of
        # "HighFanout" matches "High Fanout", "high-fanout", etc.). Set
        # `match: literal` on the rule to opt back in to strict substring.
        strict = rule.get("match") == "literal"
        missing: list[str] = []
        matched_as: dict[str, str] = {}
        for s in items:
            if strict:
                hit = s in artifact_text
                if hit:
                    matched_as[s] = s
            else:
                pat = _tolerant_token_pattern(s)
                m = re.search(pat, artifact_text, re.IGNORECASE)
                hit = m is not None
                if hit:
                    matched_as[s] = m.group(0)
            if not hit:
                missing.append(s)
        return {"passed": not missing,
                "details": {"required": items, "missing": missing,
                            "match_mode": "literal" if strict else "tolerant",
                            "matched_as": matched_as}}

    if kind == "stdout_field_equals":
        f = rule["field"]
        expected = oracle.get(f)
        actual = extracted.get(f, "")
        return {"passed": str(actual).strip() == str(expected).strip(),
                "details": {"field": f, "expected": expected, "actual": actual}}

    if kind == "stdout_field_in":
        f = rule["field"]
        allowed = oracle.get(f) or []
        actual = extracted.get(f, "")
        return {"passed": actual in allowed,
                "details": {"field": f, "allowed": allowed, "actual": actual}}

    if kind == "stdout_metric_within":
        f = rule["field"]
        try:
            actual = float(extracted.get(f, ""))
        except (TypeError, ValueError):
            return {"passed": False,
                    "details": {"reason": "extracted_not_numeric",
                                "field": f, "actual": extracted.get(f)}}
        expected = oracle.get(f)
        if expected is None:
            return {"passed": False,
                    "details": {"reason": "oracle_missing_field", "field": f}}
        tol = float(rule.get("tolerance", 0.0))
        ok = abs(actual - float(expected)) <= tol
        return {"passed": ok,
                "details": {"field": f, "expected": expected,
                            "actual": actual, "tolerance": tol}}

    return {"passed": False, "details": {"reason": f"unknown_kind:{kind}"}}


# -- artifact_signature (Phase 2: anti-fabrication primitive) --------------


class ArtifactSignature(Grader):
    """
    Assert that *path* contains every regex in the named signature family
    from ``ARTIFACT_SIGNATURES``. Designed to defeat ``cat <<EOF``-style
    fabrication: tool-emitted artifacts carry headers that paraphrasing
    cannot reproduce.

    Spec::

        - id:  lint_is_real_vivado
          type: artifact_signature
          path: outputs/lint.rpt
          signature: vivado_text_report      # key into ARTIFACT_SIGNATURES
          # OR provide inline patterns (overrides 'signature'):
          # patterns:
          #   - "Copyright ... Xilinx, Inc"
          #   - "Tool Version\\s*:\\s*Vivado v\\."
          require_all: true                  # default true; false => any
    """

    grader_type = "artifact_signature"

    def grade(self, spec: dict, ctx: GraderContext) -> GraderResult:
        p = _resolve_path(ctx, spec["path"])
        if not p.exists():
            return GraderResult(
                passed=False, score=0.0,
                details={"reason": "missing_artifact", "path": str(p)},
            )
        text = p.read_text(errors="replace")

        patterns: list[str]
        if spec.get("patterns"):
            patterns = list(spec["patterns"])
            sig_name = "<inline>"
        else:
            sig_name = spec.get("signature") or ""
            patterns = list(ARTIFACT_SIGNATURES.get(sig_name) or [])
            if not patterns:
                return GraderResult(
                    passed=False, score=0.0,
                    details={"reason": "unknown_signature",
                             "signature": sig_name,
                             "available": list(ARTIFACT_SIGNATURES.keys())},
                )

        require_all = bool(spec.get("require_all", True))
        results: list[dict] = []
        for pat in patterns:
            m = re.search(pat, text, re.MULTILINE)
            results.append({
                "pattern": pat, "matched": bool(m),
                "match": m.group(0) if m else None,
            })

        n_hit = sum(1 for r in results if r["matched"])
        passed = (n_hit == len(results)) if require_all else (n_hit > 0)
        score = (n_hit / len(results)) if results else 0.0
        return GraderResult(
            passed=passed, score=score,
            details={
                "signature": sig_name, "path": str(p),
                "matched": n_hit, "total": len(results),
                "patterns": results,
            },
        )


# -- tool_call_observed (Phase 2: did Vivado actually run?) ---------------


class ToolCallObserved(Grader):
    """
    Assert that an external tool was actually invoked during the run.

    Two complementary modes:

    * **Filesystem** (default) -- look for the side-effects a tool leaves in
      the workspace. Today's detectors are the Vivado MCP working directory
      and the Vitis ``v++`` link trail::

          <workspace>/.vivado-ai/             (created by vivado_start)
          <workspace>/.vivado-ai/vivado_*.log (created on first execute)

      Spec::

          - id:  vivado_actually_invoked
            type: tool_call_observed
            tool: vivado_mcp                   # selects detector
            min_calls: 1                       # default 1

    * **Transcript command** -- confirm a specific command was actually run
      by the agent, matched against the parsed tool-call sequence. Enabled by
      a ``command`` (or ``tool_call_observed``) key, or a ``tool`` value that
      itself carries a command (``"bash: <command>"``). The matched calls are
      surfaced in ``details.observed_commands``. Spec::

          - id:  ran_vpp
            type: tool_call_observed
            command: "bash: v++ --compile --mode hls"
            min_calls: 1
    """

    grader_type = "tool_call_observed"

    def grade(self, spec: dict, ctx: GraderContext) -> GraderResult:
        tool = spec.get("tool", "vivado_mcp")
        min_calls = int(spec.get("min_calls", 1))
        ws = ctx.workspace_dir

        # Transcript command mode: a `command`/`tool_call_observed` key, or a
        # `tool` value that itself carries a command ("bash: v++ ...").
        command = spec.get("command") or spec.get("tool_call_observed")
        if command is None and isinstance(tool, str) and ":" in tool:
            command = tool
        if command:
            return self._grade_command(str(command), min_calls, ctx)

        evidence: dict = {"tool": tool, "min_calls": min_calls}

        if tool == "vivado_mcp":
            vai = ws / ".vivado-ai"
            if not vai.exists():
                return GraderResult(
                    passed=False, score=0.0,
                    details={**evidence, "reason": ".vivado-ai/_not_present"},
                )
            logs = sorted(vai.glob("vivado_*.log"))
            jou  = sorted(vai.glob("vivado_*.jou"))
            n_calls = max(len(logs), len(jou))
            evidence.update({
                "vivado_ai_dir": str(vai),
                "log_files": [p.name for p in logs[:5]],
                "journal_files": [p.name for p in jou[:5]],
                "observed_calls": n_calls,
            })
            passed = n_calls >= min_calls
            return GraderResult(
                passed=passed, score=1.0 if passed else 0.0,
                details=evidence,
            )

        if tool == "vitis_vpp":
            # v++ leaves a _x/link / .Xil/ trail in the workspace.
            link_dir = ws / "_x" / "link"
            xil_dir  = ws / ".Xil"
            evidence.update({
                "_x_link_present": link_dir.exists(),
                ".Xil_present": xil_dir.exists(),
            })
            passed = link_dir.exists() or xil_dir.exists()
            return GraderResult(
                passed=passed, score=1.0 if passed else 0.0,
                details=evidence,
            )

        return GraderResult(
            passed=False, score=0.0,
            details={**evidence, "reason": f"unknown_tool:{tool}"},
        )

    def _grade_command(
        self, command: str, min_calls: int, ctx: GraderContext,
    ) -> GraderResult:
        """Confirm *command* was actually invoked, from the transcript."""
        from .trace import find_tool_calls, tool_commands

        client = ctx.run_meta.get("client")
        aliases = ctx.run_meta.get("mcp_server_aliases")
        if ":" in command:
            want_tool, want_cmd = command.split(":", 1)
            want_tool, want_cmd = want_tool.strip(), want_cmd.strip()
        else:
            want_tool, want_cmd = "", command.strip()

        matches = find_tool_calls(
            ctx.stdout, ctx.stderr, tool=want_tool, command=want_cmd,
            client=client, aliases=aliases,
        )
        passed = len(matches) >= min_calls
        return GraderResult(
            passed=passed, score=1.0 if passed else 0.0,
            details={
                "mode": "transcript_command",
                "expected_command": command,
                "min_calls": min_calls,
                "observed_calls": len(matches),
                "observed_commands": matches[:5],
                # Full tool/command sequence for dashboard visibility.
                "tool_sequence": tool_commands(ctx.stdout, ctx.stderr, client=client),
            },
        )


# -- metric_delta (Phase 2: directional baseline_delta) -------------------
#
# `baseline_delta` (above) is symmetric -- it passes when |value - baseline|
# is within tolerance.  For QoR-bearing skills the customer cares about
# direction: WNS must IMPROVE, util must not GROW. `metric_delta` adds
# explicit `direction` semantics on top of the same baseline plumbing.


class MetricDelta(Grader):
    """
    Compare a freshly observed metric to a captured baseline with explicit
    directional semantics.  Used by Tier 2 (QoR impact) graders.

    Spec::

        - id:  wns_improved
          type: metric_delta
          metric: wns_ns                     # key in skill_baselines
          # Provide the new value either directly...
          value: 0.123
          # ...or extract it from stdout / a report file:
          extract:
            source: file
            path: outputs/timing_summary_final.rpt
            regex: 'Slack \\(MET\\)\\s*[:=]\\s*([-+0-9.]+)\\s*ns'
          direction: improve                 # improve|regress|either
          improve_when: greater              # greater|less  (default: greater)
          min_delta_abs: 0.05                # ns (or whatever unit metric is)
          max_delta_abs: null                # cap on the OTHER side
    """

    grader_type = "metric_delta"

    def grade(self, spec: dict, ctx: GraderContext) -> GraderResult:
        meta = ctx.run_meta
        skill = meta.get("skill_name", "")
        version = meta.get("skill_version", "")
        case_id = meta.get("case_id", "")
        metric = spec["metric"]

        # Resolve the observed value.
        if "value" in spec and spec["value"] is not None:
            value = float(spec["value"])
        else:
            ex = spec.get("extract") or {}
            text = _read_source(ctx, ex.get("source", "stdout"), ex.get("path"))
            m = re.search(ex.get("regex", ""), text)
            if not m or not m.groups():
                return GraderResult(
                    passed=False, score=0.0,
                    details={"reason": "regex_no_match",
                             "metric": metric,
                             "regex": ex.get("regex", "")},
                )
            try:
                value = float(m.group(1))
            except (TypeError, ValueError):
                return GraderResult(
                    passed=False, score=0.0,
                    details={"reason": "extracted_not_numeric",
                             "metric": metric, "raw": m.group(1)},
                )

        # Resolve baseline.
        if ctx.baseline_lookup is None:
            baseline = None
        else:
            baseline = ctx.baseline_lookup(skill, version, case_id, metric)
        if baseline is None:
            # First observation: capture-only path. We pass softly so a
            # missing baseline does not turn into a hard fail on first run
            # of a new skill; the runner's baseline-capture pass picks it
            # up automatically when --capture-baseline is set.
            return GraderResult(
                passed=False, score=0.0,
                details={"reason": "missing_baseline",
                         "metric": metric, "value": value,
                         "advice": "run with --capture-baseline once"},
            )
        baseline = float(baseline)
        delta = value - baseline

        direction = (spec.get("direction") or "improve").lower()
        improve_when = (spec.get("improve_when") or "greater").lower()
        # improvement sign: +1 if "greater is better", -1 if "less is better"
        better = +1 if improve_when == "greater" else -1
        signed_improvement = better * delta

        min_d = spec.get("min_delta_abs")
        max_d = spec.get("max_delta_abs")

        ok = True
        why: list[str] = []
        if direction == "improve":
            if signed_improvement < 0:
                ok = False
                why.append(f"regressed (signed_improvement={signed_improvement:.4f})")
            elif min_d is not None and abs(signed_improvement) < float(min_d):
                ok = False
                why.append(f"|improvement|<{min_d}")
        elif direction == "regress":
            # Used to allow controlled regression (e.g., util grew by N% is OK).
            if signed_improvement > 0:
                pass  # accidentally improved, that's fine
            elif min_d is not None and abs(signed_improvement) < float(min_d):
                pass
        elif direction == "either":
            pass
        if max_d is not None and abs(delta) > float(max_d):
            ok = False
            why.append(f"|delta|>{max_d}")

        return GraderResult(
            passed=ok, score=1.0 if ok else 0.0,
            details={
                "metric": metric, "value": value, "baseline": baseline,
                "delta": delta, "direction": direction,
                "improve_when": improve_when,
                "signed_improvement": signed_improvement,
                "min_delta_abs": min_d, "max_delta_abs": max_d,
                "reason": "; ".join(why) if why else "ok",
            },
        )


